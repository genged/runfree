// Bundles the portable MCP servers under `packages/agent-runtime/src/mcp/` into
// the committed files under `packages/agent-runtime/agent/mcp/`, which the agent
// image copies. Usage:
//
//   pnpm run bundle:agent-mcp            # regenerate the committed bundle
//   pnpm run bundle:agent-mcp -- --check # rebuild to a temp dir and byte-compare
//
// The bundle is committed rather than built by `build:runtime` so the embedded
// runtime manifest stays a pure function of the repository: bundler output can
// differ between Bun versions, and CI checks that `generate:assets` reproduces
// the committed embedded assets. This script refuses any Bun other than
// REQUIRED_BUN_VERSION, and CI runs `--check` with that version, so the
// committed bytes are proved to come from the committed sources and lockfile.
//
// Set RUNFREE_BUN to a Bun binary path when `bun` on PATH is another version.

import childProcess from "node:child_process";
import crypto from "node:crypto";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import {
  PORTABLE_MCP_CONTRACT_VERSIONS,
  PORTABLE_MCP_SERVER_IDS,
  RUNFREE_MCP_BUNDLE_VERSION,
} from "../packages/agent-runtime/src/mcp/capabilities.ts";

export const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const MCP_SOURCE_DIR = path.join(repoRoot, "packages", "agent-runtime", "src", "mcp");
export const MCP_BUNDLE_DIR = path.join(repoRoot, "packages", "agent-runtime", "agent", "mcp");
const AGENT_RUNTIME_DIR = path.join(repoRoot, "packages", "agent-runtime");

// Must equal RUNFREE_BUN_VERSION in .github/workflows/verify.yml (asserted by
// scripts/agent-mcp-bundle.test.ts).
export const REQUIRED_BUN_VERSION = "1.3.14";

export const MCP_BUNDLE_ENTRIES = ["runfree-mcp", "node-repl-kernel", "self-check"] as const;

export const ALLOWED_BUNDLE_LICENSES = ["Apache-2.0", "BSD-2-Clause", "BSD-3-Clause", "ISC", "MIT"] as const;

// Packages that only the SDK's HTTP transports and OAuth client use. The STDIO
// server must never pull them in.
export const FORBIDDEN_BUNDLE_PACKAGES = [
  "@hono/node-server",
  "content-type",
  "cors",
  "cross-spawn",
  "eventsource",
  "eventsource-parser",
  "express",
  "express-rate-limit",
  "hono",
  "jose",
  "pkce-challenge",
  "raw-body",
] as const;

const BANNER = "// Generated by scripts/bundle-agent-mcp.ts from packages/agent-runtime/src/mcp. Do not edit by hand.";

export type BundledPackage = {
  integrity: string;
  license: string;
  name: string;
  version: string;
};

export type McpBundleManifest = {
  bundleVersion: string;
  bundler: { name: "bun"; version: string };
  capabilities: Array<{ contractVersion: number; id: string }>;
  files: Record<string, string>;
  packages: BundledPackage[];
  schemaVersion: 1;
  sources: Record<string, string>;
};

export function sha256(bytes: Buffer | string): string {
  return `sha256:${crypto.createHash("sha256").update(bytes).digest("hex")}`;
}

/** Every non-test TypeScript source of the portable MCP servers, by glob. */
export function mcpSourceFiles(): string[] {
  return fs.readdirSync(MCP_SOURCE_DIR)
    .filter((name) => name.endsWith(".ts") && !name.endsWith(".test.ts"))
    .sort();
}

export function mcpSourceDigests(): Record<string, string> {
  return Object.fromEntries(mcpSourceFiles().map((name) => [name, sha256(fs.readFileSync(path.join(MCP_SOURCE_DIR, name)))]));
}

/** The `resolution.integrity` pnpm-lock.yaml records for name@version. */
export function lockfileIntegrity(name: string, version: string, lockfile = fs.readFileSync(path.join(repoRoot, "pnpm-lock.yaml"), "utf8")): string | undefined {
  const packagesStart = lockfile.indexOf("\npackages:\n");
  const snapshotsStart = lockfile.indexOf("\nsnapshots:\n");
  if (packagesStart < 0 || snapshotsStart < packagesStart) throw new Error("pnpm-lock.yaml has no packages section");
  const section = lockfile.slice(packagesStart, snapshotsStart);
  const key = `${name}@${version}`;
  const header = new RegExp(`\\n  (?:'${escapeRegExp(key)}'|${escapeRegExp(key)}):\\n    resolution: \\{integrity: ([^,}]+)[,}]`);
  return header.exec(section)?.[1]?.trim();
}

function escapeRegExp(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\/]/g, "\\$&");
}

function licenseString(value: unknown): string {
  if (typeof value === "string") return value;
  if (typeof value === "object" && value !== null && typeof (value as { type?: unknown }).type === "string") {
    return (value as { type: string }).type;
  }
  return "UNKNOWN";
}

/** Maps bundler input paths to the npm packages they belong to. */
export function bundledPackagesFromInputs(inputPaths: readonly string[], baseDir: string): BundledPackage[] {
  const roots = new Map<string, string>();
  for (const input of inputPaths) {
    const absolute = path.resolve(baseDir, input);
    const marker = `${path.sep}node_modules${path.sep}`;
    const index = absolute.lastIndexOf(marker);
    if (index < 0) continue;
    const rest = absolute.slice(index + marker.length).split(path.sep);
    const name = rest[0].startsWith("@") ? `${rest[0]}/${rest[1]}` : rest[0];
    roots.set(name, path.join(absolute.slice(0, index + marker.length), ...name.split("/")));
  }
  const lockfile = fs.readFileSync(path.join(repoRoot, "pnpm-lock.yaml"), "utf8");
  return [...roots.entries()].map(([name, root]) => {
    const pkg = JSON.parse(fs.readFileSync(path.join(root, "package.json"), "utf8")) as { license?: unknown; name?: string; version?: string };
    if (pkg.name !== name || typeof pkg.version !== "string") throw new Error(`cannot identify bundled package at ${root}`);
    const integrity = lockfileIntegrity(name, pkg.version, lockfile);
    if (integrity === undefined) throw new Error(`bundled package ${name}@${pkg.version} is not pinned in pnpm-lock.yaml`);
    return { integrity, license: licenseString(pkg.license), name, version: pkg.version };
  }).sort((left, right) => left.name.localeCompare(right.name));
}

export function assertBundlePackagePolicy(packages: readonly BundledPackage[]): void {
  for (const entry of packages) {
    if (!(ALLOWED_BUNDLE_LICENSES as readonly string[]).includes(entry.license)) {
      throw new Error(`bundled package ${entry.name}@${entry.version} has license ${entry.license}, which is not in the accepted list`);
    }
    if ((FORBIDDEN_BUNDLE_PACKAGES as readonly string[]).includes(entry.name)) {
      throw new Error(`bundled package ${entry.name} belongs to the SDK's HTTP transport and must not ship`);
    }
  }
}

function bunBinary(): string {
  return process.env.RUNFREE_BUN && process.env.RUNFREE_BUN !== "" ? process.env.RUNFREE_BUN : "bun";
}

function bunVersion(bun: string): string {
  const result = childProcess.spawnSync(bun, ["--version"], { encoding: "utf8" });
  if (result.error || result.status !== 0) throw new Error(`cannot run Bun (${bun}); install Bun ${REQUIRED_BUN_VERSION} or set RUNFREE_BUN`);
  return result.stdout.trim();
}

/** Bundles the entries into outDir and returns the manifest for them. */
export function buildMcpBundle(outDir: string): McpBundleManifest {
  const bun = bunBinary();
  const version = bunVersion(bun);
  if (version !== REQUIRED_BUN_VERSION) {
    throw new Error(`bundle:agent-mcp requires Bun ${REQUIRED_BUN_VERSION} (found ${version}); set RUNFREE_BUN to a Bun ${REQUIRED_BUN_VERSION} binary`);
  }
  const work = fs.mkdtempSync(path.join(os.tmpdir(), "runfree-mcp-bundle-"));
  try {
    const metafile = path.join(work, "meta.json");
    // Relative entry paths and a fixed cwd keep the bundle's module comments
    // independent of where the checkout lives.
    const result = childProcess.spawnSync(bun, [
      "build",
      ...MCP_BUNDLE_ENTRIES.map((entry) => `src/mcp/${entry}.ts`),
      "--target=node",
      "--format=esm",
      "--minify-syntax",
      "--minify-whitespace",
      `--banner=${BANNER}`,
      "--entry-naming=[name].mjs",
      "--root=src/mcp",
      `--outdir=${path.join(work, "out")}`,
      `--metafile=${metafile}`,
    ], { cwd: AGENT_RUNTIME_DIR, encoding: "utf8" });
    if (result.error) throw result.error;
    if (result.status !== 0) throw new Error(`bun build failed:\n${result.stdout}\n${result.stderr}`);
    const meta = JSON.parse(fs.readFileSync(metafile, "utf8")) as { inputs?: Record<string, unknown> };
    const packages = bundledPackagesFromInputs(Object.keys(meta.inputs ?? {}), AGENT_RUNTIME_DIR);
    assertBundlePackagePolicy(packages);
    fs.mkdirSync(outDir, { recursive: true });
    const files: Record<string, string> = {};
    for (const entry of MCP_BUNDLE_ENTRIES) {
      const name = `${entry}.mjs`;
      const bytes = fs.readFileSync(path.join(work, "out", name));
      fs.writeFileSync(path.join(outDir, name), bytes);
      files[name] = sha256(bytes);
    }
    const manifest: McpBundleManifest = {
      schemaVersion: 1,
      bundleVersion: RUNFREE_MCP_BUNDLE_VERSION,
      bundler: { name: "bun", version },
      capabilities: PORTABLE_MCP_SERVER_IDS.map((id) => ({ id, contractVersion: PORTABLE_MCP_CONTRACT_VERSIONS[id] })),
      files,
      packages,
      sources: mcpSourceDigests(),
    };
    fs.writeFileSync(path.join(outDir, "manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`);
    return manifest;
  } finally {
    fs.rmSync(work, { recursive: true, force: true });
  }
}

export function checkCommittedMcpBundle(): void {
  const temp = fs.mkdtempSync(path.join(os.tmpdir(), "runfree-mcp-bundle-check-"));
  try {
    buildMcpBundle(temp);
    const expected = fs.readdirSync(temp).sort();
    const actual = fs.readdirSync(MCP_BUNDLE_DIR).sort();
    if (JSON.stringify(expected) !== JSON.stringify(actual)) {
      throw new Error(`committed MCP bundle files differ: expected ${expected.join(", ")}, found ${actual.join(", ")}`);
    }
    const stale = expected.filter((name) => !fs.readFileSync(path.join(temp, name)).equals(fs.readFileSync(path.join(MCP_BUNDLE_DIR, name))));
    if (stale.length > 0) {
      throw new Error(`committed MCP bundle is stale (${stale.join(", ")}); run pnpm run bundle:agent-mcp`);
    }
  } finally {
    fs.rmSync(temp, { recursive: true, force: true });
  }
}

if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    if (process.argv.includes("--check")) {
      checkCommittedMcpBundle();
      console.log("portable MCP bundle is current");
    } else {
      fs.rmSync(MCP_BUNDLE_DIR, { recursive: true, force: true });
      const manifest = buildMcpBundle(MCP_BUNDLE_DIR);
      console.log(`bundled ${Object.keys(manifest.files).join(", ")} (${manifest.packages.map((entry) => `${entry.name}@${entry.version}`).join(", ")})`);
    }
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
  }
}
