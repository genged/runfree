/**
 * The direct children of a top-level Compose mapping, in file order.
 *
 * The structural contract is validated against `docker compose config` by
 * `scripts/validate-runtime-compose.ts` (`make test-templates`), which needs a
 * Docker CLI. This reads the shipped template without one, so it stays a
 * two-space-indent scan rather than a parse; the template is generated by
 * `scripts/build-runtime.ts` from a fixed source, so its indentation is not a
 * variable. A reformatted template makes this throw rather than pass vacuously.
 */
function composeTopLevelKeys(compose: string, section: string): string[] {
  const lines = compose.split("\n");
  const start = lines.indexOf(`${section}:`);
  if (start === -1) throw new Error(`compose template has no top-level ${section}: mapping`);
  const keys: string[] = [];
  for (const line of lines.slice(start + 1)) {
    if (line.trim() === "" || line.startsWith("#")) continue;
    if (!line.startsWith("  ")) break;
    const key = /^ {2}([A-Za-z0-9_.-]+):/.exec(line);
    if (key) keys.push(key[1]);
  }
  if (keys.length === 0) throw new Error(`compose template ${section}: mapping parsed as empty`);
  return keys;
}

