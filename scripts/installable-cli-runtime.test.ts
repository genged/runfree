  test("typescript cli imports a clipboard image into host state and prints the container path", () => {
    const source = path.join(tmpBase, "clip.png");
    fs.writeFileSync(source, Buffer.from([0x89, 0x50, 0x4e, 0x47, 1, 2, 3]));

    const result = runTsCli(["inbox", "paste"], {
      RUNFREE_TEST_CLIPBOARD_IMAGE_PATH: source,
      RUNFREE_TEST_INBOX_RANDOM: "a8f3",
    });

    expect(result.status, result.stderr).toBe(0);
    expect(result.stdout.trim()).toMatch(/^\/runfree\/inbox\/clip-\d{4}-\d{2}-\d{2}-\d{6}-a8f3\.png$/);
    const stateRoot = path.join(tmpBase, "xdg-state", "runfree", "projects");
    const files = fs.readdirSync(stateRoot, { recursive: true }).map(String);
    expect(files.some((entry) => /inbox\/clip-.*-a8f3\.png$/.test(entry))).toBe(true);
    expect(fs.existsSync(path.join(tmp, ".runfree"))).toBe(false);
  });

  test("typescript cli still prints the imported image path when clipboard copy fails", () => {
    const source = path.join(tmpBase, "clip.png");
    fs.writeFileSync(source, Buffer.from([0x89, 0x50, 0x4e, 0x47, 1, 2, 3]));

    const result = runTsCli(["inbox", "paste", "--copy"], {
      RUNFREE_TEST_CLIPBOARD_COPY_ERROR: "forced copy failure",
      RUNFREE_TEST_CLIPBOARD_IMAGE_PATH: source,
      RUNFREE_TEST_INBOX_RANDOM: "a8f4",
    });

    expect(result.status).toBe(0);
    expect(result.stdout.trim()).toMatch(/^\/runfree\/inbox\/clip-\d{4}-\d{2}-\d{2}-\d{6}-a8f4\.png$/);
    expect(result.stderr).toContain("warning: image imported at /runfree/inbox/");
    expect(result.stderr).toContain("copy failed:");
  });

  test("typescript cli runs admin commands in-process against the project policy", () => {
    const init = runTsCli(["init"]);
    expect(init.status, init.stderr).toBe(0);

    const fakeBin = path.join(tmp, "fake-bin");
    fs.mkdirSync(fakeBin);
    fs.writeFileSync(path.join(fakeBin, "docker"), "#!/bin/sh\nexit 0\n");
    fs.chmodSync(path.join(fakeBin, "docker"), 0o755);

    const result = runTsCli([
      "host",
      "add",
      "example.org",
      "--no-reload",
    ], { PATH: `${fakeBin}:${process.env.PATH ?? ""}` });

    expect(result.status, result.stderr).toBe(0);
    expect(result.stdout).toContain("example.org updated");
    expect(result.stdout).toContain("effective policy: unchanged (--no-reload)");
    expect(fs.readFileSync(path.join(tmp, ".runfree/network-policy.json"), "utf8")).toContain("example.org");
  });

